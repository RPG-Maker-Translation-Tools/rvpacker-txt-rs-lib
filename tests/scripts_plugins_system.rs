//! Scripts and plugins have no ids of their own, so their translations follow their names. A translated string goes back
//! into Ruby code as a valid literal, and a plugin file keeps its layout. The game title is translated like any line.

use marshal_rs::dump;
use rvpacker_txt_rs_lib::{EngineType, Mode, ProcessedData, core::Base, types::Scripts};

fn scripts_file(scripts: &[(&str, &str)]) -> Vec<u8> {
    let numbers = (0..scripts.len() as i32).collect();
    let contents = scripts.iter().map(|(_, code)| (*code).to_owned()).collect();
    let names = scripts.iter().map(|(name, _)| (*name).to_owned()).collect();

    dump(&Base::encode_scripts(&Scripts::new(numbers, contents, names)))
}

fn codes(data: &ProcessedData) -> Vec<String> {
    let bytes: &[u8] = data.as_ref();
    let arena = marshal_rs::load(bytes).unwrap().into_owned();

    Base::decode_scripts(&arena, arena.root(), None).unwrap().contents
}

fn text(data: &ProcessedData) -> String {
    let bytes: &[u8] = data.as_ref();

    String::from_utf8(bytes.to_vec()).unwrap()
}

fn read(engine: EngineType, content: &[u8], plugins: bool) -> String {
    let mut base = Base::new(Mode::read(), engine);
    let data = if plugins {
        base.process_plugins(content, None)
    } else {
        base.process_scripts(content, None)
    };

    text(&data.unwrap().unwrap())
}

mod scripts {
    use super::*;

    fn write(content: &[u8], translation: &str) -> Vec<String> {
        let data = Base::new(Mode::Write, EngineType::VXAce)
            .process_scripts(content, Some(translation))
            .unwrap()
            .unwrap();

        codes(&data)
    }

    #[test]
    fn a_quote_in_a_translation_is_escaped() {
        let content = scripts_file(&[("Main", "x = 'Gold'\ny = \"Gold\"\n")]);
        let translation = read(EngineType::VXAce, &content, false).replace("Gold<#>", "Gold<#>It's \"gold\"");

        assert_eq!(
            write(&content, &translation),
            [r#"x = 'It\'s "gold"'"#.to_owned() + "\n" + r#"y = "It's \"gold\"""# + "\n"]
        );
    }

    #[test]
    fn an_escaped_quote_in_a_translation_is_left_alone() {
        let content = scripts_file(&[("Main", "x = 'Gold'\n")]);
        let translation = read(EngineType::VXAce, &content, false).replace("Gold<#>", r"Gold<#>It\'s gold");

        assert_eq!(write(&content, &translation), [r"x = 'It\'s gold'".to_owned() + "\n"]);
    }

    #[test]
    fn a_script_inserted_into_the_game_does_not_shift_the_translations() {
        let before = scripts_file(&[("Alpha", "a = 'First'\n"), ("Beta", "b = 'Second'\n")]);
        let translation = read(EngineType::VXAce, &before, false)
            .replace("First<#>", "First<#>Первый")
            .replace("Second<#>", "Second<#>Второй");

        let after = scripts_file(&[
            ("Alpha", "a = 'First'\n"),
            ("Inserted", "i = 'Fresh'\n"),
            ("Beta", "b = 'Second'\n"),
        ]);

        assert_eq!(
            write(&after, &translation),
            ["a = 'Первый'\n", "i = 'Fresh'\n", "b = 'Второй'\n"]
        );
    }
}

mod plugins {
    use super::*;

    const GAME: &str = r#"// Generated by RPG Maker.
// Do not edit this file directly = please.
var $plugins =
[
{"name":"Alpha","status":true,"description":"","parameters":{"text":"First"}},
{"name":"Beta","status":true,"description":"","parameters":{"text":"Second"}}
];
"#;

    const GAME_WITH_ONE_INSERTED: &str = r#"// Generated by RPG Maker.
// Do not edit this file directly = please.
var $plugins =
[
{"name":"Alpha","status":true,"description":"","parameters":{"text":"First"}},
{"name":"Inserted","status":true,"description":"","parameters":{"text":"Fresh"}},
{"name":"Beta","status":true,"description":"","parameters":{"text":"Second"}}
];
"#;
    #[test]
    fn a_plugin_inserted_into_the_game_does_not_shift_the_translations() {
        let translation = read(EngineType::MVMZ, GAME.as_bytes(), true)
            .replace("First<#>", "First<#>Первый")
            .replace("Second<#>", "Second<#>Второй");

        let data = Base::new(Mode::Write, EngineType::MVMZ)
            .process_plugins(GAME_WITH_ONE_INSERTED.as_bytes(), Some(&translation))
            .unwrap()
            .unwrap();

        assert_eq!(
            text(&data),
            GAME_WITH_ONE_INSERTED
                .replace("First", "Первый")
                .replace("Second", "Второй")
        );
    }

    #[test]
    fn the_file_keeps_its_layout() {
        let translation = read(EngineType::MVMZ, GAME.as_bytes(), true).replace("First<#>", "First<#>Первый");

        let data = Base::new(Mode::Write, EngineType::MVMZ)
            .process_plugins(GAME.as_bytes(), Some(&translation))
            .unwrap()
            .unwrap();

        assert_eq!(text(&data), GAME.replace("First", "Первый"));
    }
}

mod system {
    use super::*;

    const SYSTEM: &str = r#"{"gameTitle":"Foo"}"#;
    const TRANSLATION: &str = "<!>ID<#>8\n<!>NAME<#>Game Title\nFoo<#>Фу\n";

    fn title(base: &mut Base) -> String {
        let data = base
            .process_system(SYSTEM.as_bytes(), Some(TRANSLATION))
            .unwrap()
            .unwrap();

        serde_json::from_str::<serde_json::Value>(&text(&data)).unwrap()["gameTitle"]
            .as_str()
            .unwrap()
            .to_owned()
    }

    #[test]
    fn the_title_is_translated_like_any_line() {
        assert_eq!(title(&mut Base::new(Mode::Write, EngineType::MVMZ)), "Фу");
    }

    #[test]
    fn a_title_set_by_the_caller_wins() {
        let mut base = Base::new(Mode::Write, EngineType::MVMZ);
        base.set_game_title("Бар");

        assert_eq!(title(&mut base), "Бар");
    }
}
